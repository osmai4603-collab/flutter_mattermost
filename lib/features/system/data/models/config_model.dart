    required super.LocalizationSettings,
    required super.SamlSettings,
    required super.NativeAppSettings,
    required super.ClusterSettings,
    required super.MetricsSettings,
    required super.AnalyticsSettings,
  });

  factory ConfigModel.fromMap(Map<String, dynamic> map) {
    return ConfigModel(
      ServiceSettings: map["ServiceSettings"] as Map<String, dynamic>?,
      TeamSettings: map["TeamSettings"] as Map<String, dynamic>?,
      SqlSettings: map["SqlSettings"] as Map<String, dynamic>?,

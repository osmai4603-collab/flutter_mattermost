      GoogleSettings: map["GoogleSettings"] as Map<String, dynamic>?,
      Office365Settings: map["Office365Settings"] as Map<String, dynamic>?,
      LdapSettings: map["LdapSettings"] as Map<String, dynamic>?,
      ComplianceSettings: map["ComplianceSettings"] as Map<String, dynamic>?,

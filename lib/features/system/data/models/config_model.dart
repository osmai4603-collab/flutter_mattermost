      ServiceSettings: entity.ServiceSettings,
      TeamSettings: entity.TeamSettings,
      SqlSettings: entity.SqlSettings,
      LogSettings: entity.LogSettings,
      PasswordSettings: entity.PasswordSettings,
      FileSettings: entity.FileSettings,

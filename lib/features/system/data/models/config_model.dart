    required super.TeamSettings,
    required super.SqlSettings,
    required super.LogSettings,
    required super.PasswordSettings,
    required super.FileSettings,
    required super.EmailSettings,
    required super.RateLimitSettings,
    required super.PrivacySettings,
    required super.SupportSettings,
    required super.GitLabSettings,
    required super.GoogleSettings,
    required super.Office365Settings,
    required super.LdapSettings,

import 'package:flutter_mattermost/features/auth/domain/entities/user_report_entity.dart';

final class UserReportModel extends UserReportEntity {
  const UserReportModel({
    required super.id,
    required super.create_at,
    required super.update_at,
    required super.delete_at,
    required super.username,
    required super.auth_data,
    required super.auth_service,
    required super.email,
    required super.nickname,
    required super.first_name,
    required super.last_name,
    required super.position,
    required super.roles,
    required super.locale,
    required super.timezone,
    required super.disable_welcome_email,
    required super.last_login,
    required super.last_status_at,
    required super.last_post_date,
    required super.days_active,
    required super.total_posts,
  });

  factory UserReportModel.fromMap(Map<String, dynamic> map) {
    return UserReportModel(
      id: map["id"] as String?,
      create_at: (map["create_at"] as num?)?.toInt(),
      update_at: (map["update_at"] as num?)?.toInt(),
      delete_at: (map["delete_at"] as num?)?.toInt(),
      username: map["username"] as String?,
      auth_data: map["auth_data"] as String?,
      auth_service: map["auth_service"] as String?,
      email: map["email"] as String?,
      nickname: map["nickname"] as String?,
      first_name: map["first_name"] as String?,
      last_name: map["last_name"] as String?,
      position: map["position"] as String?,
      roles: map["roles"] as String?,
      locale: map["locale"] as String?,
      timezone: map["timezone"] as Map<String, dynamic>?,
      disable_welcome_email: map["disable_welcome_email"] as bool?,
      last_login: (map["last_login"] as num?)?.toInt(),
      last_status_at: (map["last_status_at"] as num?)?.toInt(),
      last_post_date: (map["last_post_date"] as num?)?.toInt(),
      days_active: (map["days_active"] as num?)?.toInt(),
      total_posts: (map["total_posts"] as num?)?.toInt(),
    );
  }

  Map<String, dynamic> toMap() {
    return {
      "id": id,
      "create_at": create_at,
      "update_at": update_at,
      "delete_at": delete_at,
      "username": username,
      "auth_data": auth_data,
      "auth_service": auth_service,
      "email": email,
      "nickname": nickname,
      "first_name": first_name,
      "last_name": last_name,
      "position": position,
      "roles": roles,
      "locale": locale,
      "timezone": timezone,
      "disable_welcome_email": disable_welcome_email,
      "last_login": last_login,
      "last_status_at": last_status_at,
      "last_post_date": last_post_date,
      "days_active": days_active,
      "total_posts": total_posts,
    };
  }

  factory UserReportModel.fromEntity(UserReportEntity entity) {
    return UserReportModel(
      id: entity.id,
      create_at: entity.create_at,
      update_at: entity.update_at,
      delete_at: entity.delete_at,
      username: entity.username,
      auth_data: entity.auth_data,
      auth_service: entity.auth_service,
      email: entity.email,
      nickname: entity.nickname,
      first_name: entity.first_name,
      last_name: entity.last_name,
      position: entity.position,
      roles: entity.roles,
      locale: entity.locale,
      timezone: entity.timezone,
      disable_welcome_email: entity.disable_welcome_email,
      last_login: entity.last_login,
      last_status_at: entity.last_status_at,
      last_post_date: entity.last_post_date,
      days_active: entity.days_active,
      total_posts: entity.total_posts,
    );
  }

  @override
  UserReportModel copyWith({
    String? id,
    int? create_at,
    int? update_at,
    int? delete_at,
    String? username,
    String? auth_data,
    String? auth_service,
    String? email,
    String? nickname,
    String? first_name,
    String? last_name,
    String? position,
    String? roles,
    String? locale,
    Map<String, dynamic>? timezone,
    bool? disable_welcome_email,
    int? last_login,
    int? last_status_at,
    int? last_post_date,
    int? days_active,
    int? total_posts,
  }) {
    return UserReportModel(
      id: id ?? this.id,
      create_at: create_at ?? this.create_at,
      update_at: update_at ?? this.update_at,
      delete_at: delete_at ?? this.delete_at,
      username: username ?? this.username,
      auth_data: auth_data ?? this.auth_data,
      auth_service: auth_service ?? this.auth_service,
      email: email ?? this.email,
      nickname: nickname ?? this.nickname,
      first_name: first_name ?? this.first_name,
      last_name: last_name ?? this.last_name,
      position: position ?? this.position,
      roles: roles ?? this.roles,
      locale: locale ?? this.locale,
      timezone: timezone ?? this.timezone,
      disable_welcome_email: disable_welcome_email ?? this.disable_welcome_email,
      last_login: last_login ?? this.last_login,
      last_status_at: last_status_at ?? this.last_status_at,
      last_post_date: last_post_date ?? this.last_post_date,
      days_active: days_active ?? this.days_active,
      total_posts: total_posts ?? this.total_posts,
    );
  }

  UserReportEntity toEntity() => UserReportEntity(
        id: id,
        create_at: create_at,
        update_at: update_at,
        delete_at: delete_at,
        username: username,
        auth_data: auth_data,
        auth_service: auth_service,
        email: email,
        nickname: nickname,
        first_name: first_name,
        last_name: last_name,
        position: position,
        roles: roles,
        locale: locale,
        timezone: timezone,
        disable_welcome_email: disable_welcome_email,
        last_login: last_login,
        last_status_at: last_status_at,
        last_post_date: last_post_date,
        days_active: days_active,
        total_posts: total_posts,
      );
}
